import 'dotenv/config';
import { createRequire } from 'node:module';
import { writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { dirname } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));

const _require = createRequire(import.meta.url);
const { Client, DefaultRequestExecutor } = _require('@okta/okta-sdk-nodejs') as {
  Client: new (opts: Record<string, unknown>) => Record<string, unknown>;
  DefaultRequestExecutor: new () => unknown;
};

const key = _require(process.env.OKTA_PRIVATE_KEY_PATH!) as Record<string, unknown>;

const client = new Client({
  orgUrl: `https://${process.env.OKTA_DOMAIN}`,
  authorizationMode: 'PrivateKey',
  clientId: process.env.OKTA_CLIENT_ID,
  scopes: (process.env.OKTA_SCOPES ?? '').split(' ').filter(Boolean),
  privateKey: key,
  requestExecutor: new DefaultRequestExecutor(),
});

const TARGET_APIS = [
  'userApi',
  'groupApi',
  'applicationApi',
  'systemLogApi',
  'policyApi',
  'roleAssignmentApi',
  'roleTargetApi',
  'deviceApi',
  'authenticatorApi',
];

function getMethods(obj: object): string[] {
  return Object.getOwnPropertyNames(Object.getPrototypeOf(obj))
    .filter(m => m !== 'constructor' && typeof (obj as Record<string, unknown>)[m] === 'function')
    .sort();
}

const lines: string[] = [
  '# Okta SDK v8 - Available API Methods',
  '',
  'Generated by `scripts/probe-sdk-methods.ts`. Reference this file when implementing tool handlers.',
  'Do not invent method names; use only what appears here.',
  '',
];

for (const apiName of TARGET_APIS) {
  const api = client[apiName] as object | undefined;
  if (!api) {
    lines.push(`## ${apiName}`, '', '_Not found on client instance._', '');
    continue;
  }
  const methods = getMethods(api);
  lines.push(`## ${apiName}`, '');
  for (const m of methods) {
    lines.push(`- \`${m}\``);
  }
  lines.push('');
}

// Also list every API on the client for reference
lines.push('## All API properties on client', '');
const allApis = Object.keys(client).filter(k => k.endsWith('Api')).sort();
for (const a of allApis) {
  lines.push(`- \`${a}\``);
}
lines.push('');

const outDir = join(__dirname, '..', 'docs');
mkdirSync(outDir, { recursive: true });
const outPath = join(outDir, 'okta-sdk-v8-methods.md');
writeFileSync(outPath, lines.join('\n'), 'utf-8');

process.stdout.write(`Written to ${outPath}\n`);
